import { test, expect as baseExpect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { createResumeDocx } from "../../src/lib/resumeExport.js";

const api = "http://127.0.0.1:3100";
const expect = baseExpect.configure({ timeout: 20000 });
test.use({ trace: "retain-on-failure" });

test("resume journey saves reviewed versions, exports PDF and tracks an adapted application", async ({ page }, testInfo) => {
  test.setTimeout(180000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const email = `journey-${Date.now()}-${Math.random().toString(36).slice(2)}@example.com`;
  const headers = { "x-forwarded-for": `10.92.${Math.floor(Math.random() * 250)}.${Math.floor(Math.random() * 250)}` };
  const registered = await page.request.post(`${api}/api/auth/register`, { headers, data: { email, name: "Ana Lima", password: "journey-test-password-123" } });
  expect(registered.status()).toBe(201);
  const { dev_code } = await registered.json();
  const verified = await page.request.post(`${api}/api/auth/verify-code`, { headers, data: { email, code: dev_code } });
  expect(verified.status()).toBe(200);
  const session = await verified.json();
  await page.addInitScript(({ user, expires_at }) => {
    localStorage.setItem("career-ai-splash-seen", "true");
    localStorage.setItem(`career-ai-onboarding-v1:${user.id}`, "complete");
    localStorage.setItem("career-ai-current-user", JSON.stringify(user));
    localStorage.setItem("career-ai-auth-expires-at", expires_at);
    localStorage.setItem("logged", "true");
  }, session);
  const csrf = await (await page.request.get(`${api}/api/auth/csrf`)).json();
  const mutationHeaders = { ...headers, "x-csrf-token": csrf.csrf_token };
  const source = "Ana Lima\n\nResumo profissional\nDesenvolvedora frontend com React, JavaScript, TypeScript, HTML, CSS e Git.\n\nExperiência profissional\nResponsável por testes de interfaces. Reduzi erros em 20%.";
  const docx = createResumeDocx(source);
  const uploaded = await page.request.post(`${api}/api/analysis`, { headers: mutationHeaders, multipart: { privacyConsent: "true", resume: { name: "ana.docx", mimeType: docx.type, buffer: Buffer.from(await docx.arrayBuffer()) } } });
  expect(uploaded.status(), await uploaded.text()).toBe(200);
  const { analysis } = await uploaded.json();
  await page.goto(`/analysis?id=${analysis.id}`);
  await expect(page.getByText("Análise por regras locais.", { exact: false })).toBeVisible();
  await page.getByRole("link", { name: "Editar currículo e versões" }).click();
  const editor = page.getByLabel("Currículo", { exact: true });
  await expect(editor).toHaveValue(/Ana Lima/);
  const original = await editor.inputValue();
  await page.getByRole("button", { name: "Propor revisão" }).click();
  await expect(page.getByLabel("Proposta para aprovação")).toBeVisible();
  await expect(editor).toHaveValue(original);
  const revised = original.replace("Responsável por testes de interfaces", "Executei testes de interfaces");
  await page.getByLabel("Proposta para aprovação").fill(revised);
  await page.getByRole("button", { name: "Aprovar alteração" }).click();
  await expect(editor).toHaveValue(revised);
  await page.getByRole("tab", { name: "Comparar", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Antes", exact: true })).toBeVisible();
  await page.getByLabel("Nome da nova versão").fill("Ana - Revisão aprovada");
  await page.getByRole("button", { name: "Salvar versão", exact: true }).click();
  await expect(page.getByText("Sem alterações pendentes", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("resume-editor.png"), fullPage: true });
  const accessibility = await new AxeBuilder({ page }).include("main").withTags(["wcag2a", "wcag2aa"]).analyze();
  expect(accessibility.violations).toEqual([]);
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Baixar PDF", exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/\.pdf$/);
  await download.saveAs(testInfo.outputPath("resume.pdf"));
  await page.reload();
  await expect(page.getByLabel("Currículo", { exact: true })).toHaveValue(revised);

  const job = { id: `job-${analysis.id}`, external_id: `job-${analysis.id}`, title: "Desenvolvedora React", company: "Empresa de teste", description: "React, testes automatizados e Git.", is_real: true, url: "https://example.com/jobs/react", source: "Fixture", match_evaluated: false };
  const saved = await page.request.post(`${api}/api/jobs/tracked`, { headers: mutationHeaders, data: { job, analysis_id: analysis.id } });
  expect(saved.status()).toBe(201);
  await page.goto("/jobs");
  await page.getByRole("tab", { name: /Minha jornada/ }).click();
  await page.getByRole("button", { name: "Adaptar currículo", exact: true }).click();
  await page.getByRole("button", { name: "Abrir revisão", exact: true }).click();
  await expect(page.getByLabel("Requisitos da vaga")).toHaveValue(job.description);
  await expect(page.getByLabel("Currículo", { exact: true })).toHaveValue(revised);
  await page.getByRole("button", { name: "Salvar versão", exact: true }).click();
  await expect(page.getByText("Versão salva e vinculada à candidatura", { exact: true })).toBeVisible();
  await page.goto("/jobs");
  await page.getByRole("tab", { name: /Minha jornada/ }).click();
  await page.getByRole("button", { name: "Candidatura", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Etapa da candidatura").selectOption("applied");
  await dialog.getByLabel("Anotações").fill("Contato com a equipe de recrutamento.");
  await dialog.getByLabel("Próxima ação").fill("Confirmar entrevista");
  await dialog.getByLabel("Lembrete na jornada").fill("2026-01-10T10:00");
  await dialog.getByLabel("Entrevista", { exact: true }).fill("2027-01-10T10:00");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("application-dialog.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Salvar candidatura", exact: true }).click();
  await expect(dialog).toBeHidden();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Lembretes pendentes (1)" })).toBeVisible();
  await page.getByRole("button", { name: "Abrir candidatura", exact: true }).click();
  await expect(page.getByLabel("Anotações")).toHaveValue("Contato com a equipe de recrutamento.");
  await expect(page.getByText(/Versão enviada:/)).toBeVisible();
  expect(errors).toEqual([]);
});
